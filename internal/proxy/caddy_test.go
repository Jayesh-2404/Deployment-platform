func TestApplyIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	config := testConfig(dir)

	writer, err := NewCaddyWriter(config)
	if err != nil {
		t.Fatalf("NewCaddyWriter() error = %v", err)
	}
	var calls []reloadCall
	writer.reload = stubReload(nil, &calls)

	routes := []Route{
		{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"},
		{Host: testDashboardHost, Upstream: "127.0.0.1:8080", Dashboard: true},
	}
	if err := writer.Apply(routes); err != nil {
		t.Fatalf("Apply() error = %v", err)
	}
	first, err := os.ReadFile(config.CaddyfilePath)
	if err != nil {
		t.Fatalf("ReadFile() error = %v", err)
	}
	// Same routes, reverse order.
	if err := writer.Apply([]Route{routes[1], routes[0]}); err != nil {
		t.Fatalf("Apply() error = %v", err)
	}
	second, err := os.ReadFile(config.CaddyfilePath)
	if err != nil {
		t.Fatalf("ReadFile() error = %v", err)
	}
	if string(first) != string(second) {
		t.Errorf("second Apply() = %q, want %q", string(second), string(first))
	}
	if len(calls) != 2 {
		t.Errorf("reload calls = %d, want 2", len(calls))
	}

	// No temp file may survive a successful apply.
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("ReadDir() error = %v", err)
	}
	if len(entries) != 1 || entries[0].Name() != filepath.Base(config.CaddyfilePath) {
		t.Errorf("dir entries = %v, want only %q", entries, filepath.Base(config.CaddyfilePath))
	}
}

