func TestRenderIsDeterministic(t *testing.T) {
	config := testConfig(t.TempDir())
	routes := []Route{
		{Host: "pay-api.example.com", Upstream: "127.0.0.1:32770"},
		{Host: testDashboardHost, Upstream: "127.0.0.1:8080", Dashboard: true},
		{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"},
	}

	first := Render(config, routes)
	for i := 0; i < 5; i++ {
		if got := Render(config, routes); got != first {
			t.Fatalf("Render() call %d = %q, want %q", i+2, got, first)
		}
	}

	// The same routes in a different order must render the same bytes, which is
	// the property that keeps an unchanged deploy from reloading the proxy.
	shuffled := []Route{routes[2], routes[0], routes[1]}
	if got := Render(config, shuffled); got != first {
		t.Errorf("Render(shuffled) = %q, want %q", got, first)
	}

	// Render must not sort the caller's slice in place.
	if routes[0].Host != "pay-api.example.com" {
		t.Errorf("Render() reordered the caller's routes: routes[0].Host = %q", routes[0].Host)
	}
}

