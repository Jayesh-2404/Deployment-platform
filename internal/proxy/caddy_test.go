const (
	testBaseDomain    = "example.com"
	testDashboardHost = "deploy.example.com"
	testACMEEmail     = "ops@example.com"
)

// testConfig returns a config pointing at a path inside dir.
func testConfig(dir string) Config {
	return Config{
		BaseDomain:    testBaseDomain,
		DashboardHost: testDashboardHost,
		ACMEEmail:     testACMEEmail,
		CaddyfilePath: filepath.Join(dir, "Caddyfile"),
		ReloadBinary:  "caddy",
		ReloadArgs:    []string{"reload", "--config", filepath.Join(dir, "Caddyfile")},
	}
}

type reloadCall struct {
	binary string
	args   []string
}

// stubReload returns a reload implementation that records every invocation and
// then fails with failWith, so a test can assert both the arguments used and
// the error reaching Apply.
func stubReload(failWith error, calls *[]reloadCall) func(context.Context, string, []string) error {
	return func(_ context.Context, binary string, args []string) error {
		*calls = append(*calls, reloadCall{binary: binary, args: args})
		return failWith
	}
}

func TestRouteValidate(t *testing.T) {
	cases := []struct {
		name    string
		route   Route
		wantErr string
	}{
		{
			name:  "valid project route",
			route: Route{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"},
		},
		{
			name:  "valid dashboard route",
			route: Route{Host: testDashboardHost, Upstream: "127.0.0.1:8080", Dashboard: true},
		},
		{
			name:    "empty host",
			route:   Route{Upstream: "127.0.0.1:32768"},
			wantErr: "host is required",
		},
		{
			name:    "whitespace host",
			route:   Route{Host: "   ", Upstream: "127.0.0.1:32768"},
			wantErr: "host is required",
		},
		{
			name:    "empty upstream",
			route:   Route{Host: "my-app.example.com"},
			wantErr: "upstream is required",
		},
		{
			name:    "whitespace upstream",
			route:   Route{Host: "my-app.example.com", Upstream: "  "},
			wantErr: "upstream is required",
		},
		{
			name:    "host with a space",
			route:   Route{Host: "foo bar", Upstream: "127.0.0.1:32768"},
			wantErr: `host "foo bar" is not a valid hostname`,
		},
		{
			name:    "host with an empty label",
			route:   Route{Host: "foo..bar", Upstream: "127.0.0.1:32768"},
			wantErr: `host "foo..bar" is not a valid hostname`,
		},
		{
			name:    "host with a leading dot",
			route:   Route{Host: ".foo", Upstream: "127.0.0.1:32768"},
			wantErr: `host ".foo" is not a valid hostname`,
		},
		{
			name:    "host with a trailing dot",
			route:   Route{Host: "foo.", Upstream: "127.0.0.1:32768"},
			wantErr: `host "foo." is not a valid hostname`,
		},
		{
			name:    "host with an underscore",
			route:   Route{Host: "my_app.example.com", Upstream: "127.0.0.1:32768"},
			wantErr: `host "my_app.example.com" is not a valid hostname`,
		},
		{
			name:    "upstream without a port",
			route:   Route{Host: "my-app.example.com", Upstream: "notaport"},
			wantErr: `upstream "notaport" must be host:port`,
		},
		{
			name:    "upstream with a non numeric port",
			route:   Route{Host: "my-app.example.com", Upstream: "host:abc"},
			wantErr: `upstream "host:abc" must be host:port`,
		},
		{
			name:    "upstream with two ports",
			route:   Route{Host: "my-app.example.com", Upstream: "host:80:90"},
			wantErr: `upstream "host:80:90" must be host:port`,
		},
		{
			name:    "upstream with an empty port",
			route:   Route{Host: "my-app.example.com", Upstream: "host:"},
			wantErr: `upstream "host:" must be host:port`,
		},
		{
			name:    "upstream with an empty host",
			route:   Route{Host: "my-app.example.com", Upstream: ":8080"},
			wantErr: `upstream ":8080" must be host:port`,
		},
		{
			name:    "upstream port out of range",
			route:   Route{Host: "my-app.example.com", Upstream: "127.0.0.1:70000"},
			wantErr: `upstream "127.0.0.1:70000" must be host:port`,
		},
		{
			name:    "host reported before upstream",
			route:   Route{Host: "foo bar"},
			wantErr: `host "foo bar" is not a valid hostname`,
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			err := testCase.route.Validate()
			if testCase.wantErr == "" {
				if err != nil {
					t.Fatalf("Route.Validate() error = %v, want nil", err)
				}
				return
			}
			if err == nil {
				t.Fatalf("Route.Validate() error = nil, want %q", testCase.wantErr)
			}
			if err.Error() != testCase.wantErr {
				t.Fatalf("Route.Validate() error = %q, want %q", err.Error(), testCase.wantErr)
			}
		})
	}
}

