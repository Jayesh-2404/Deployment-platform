func TestApplyRejectsInvalidRoutesWithoutWriting(t *testing.T) {
	cases := []struct {
		name    string
		routes  []Route
		wantErr string
	}{
		{
			name:    "invalid route",
			routes:  []Route{{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"}, {Host: "foo..bar", Upstream: "127.0.0.1:32769"}},
			wantErr: `route 1: host "foo..bar" is not a valid hostname`,
		},
		{
			name:    "empty host",
			routes:  []Route{{Host: "", Upstream: "127.0.0.1:32768"}},
			wantErr: "route 0: host is required",
		},
		{
			name:    "invalid upstream",
			routes:  []Route{{Host: "my-app.example.com", Upstream: "127.0.0.1"}},
			wantErr: `route 0: upstream "127.0.0.1" must be host:port`,
		},
		{
			name: "duplicate host",
			routes: []Route{
				{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"},
				{Host: "my-app.example.com", Upstream: "127.0.0.1:32769"},
			},
			wantErr: `duplicate route host "my-app.example.com"`,
		},
		{
			name: "duplicate host with different case",
			routes: []Route{
				{Host: "my-app.example.com", Upstream: "127.0.0.1:32768"},
				{Host: "My-App.example.com", Upstream: "127.0.0.1:32769"},
			},
			wantErr: `duplicate route host "My-App.example.com"`,
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			dir := t.TempDir()
			config := testConfig(dir)
			var calls []reloadCall

			writer, err := NewCaddyWriter(config)
			if err != nil {
				t.Fatalf("NewCaddyWriter() error = %v", err)
			}
			writer.reload = stubReload(nil, &calls)

			if err := writer.Apply(testCase.routes); err == nil {
				t.Fatalf("Apply() error = nil, want %q", testCase.wantErr)
			} else if err.Error() != testCase.wantErr {
				t.Fatalf("Apply() error = %q, want %q", err.Error(), testCase.wantErr)
			}

			if _, err := os.Stat(config.CaddyfilePath); !os.IsNotExist(err) {
				t.Errorf("os.Stat(%q) error = %v, want not exist", config.CaddyfilePath, err)
			}
			if len(calls) != 0 {
				t.Errorf("reload calls = %d, want 0", len(calls))
			}
			entries, err := os.ReadDir(dir)
			if err != nil {
				t.Fatalf("ReadDir() error = %v", err)
			}
			if len(entries) != 0 {
				t.Errorf("dir contains %d entries, want 0", len(entries))
			}
		})
	}
}

